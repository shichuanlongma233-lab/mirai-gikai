import "server-only";

import { FOLLOW_UP_DEPTH_LIMIT_RULE } from "@/features/interview-config/shared/utils/default-questions-template";

/**
 * 資料からトピック記事とインタビュー設定の下書きを作るためのプロンプト。
 */
export function buildTopicDraftPrompt(params: {
  documentText: string;
  instructions?: string;
}): { system: string; user: string } {
  const { documentText, instructions } = params;

  const system = `あなたは、日本の文化・商品・サービスを海外に展開するための「AIインタビュー型市場調査」を設計する専門家です。
回答者は海外在住の一般の人々で、日本語を読めない前提です（記事・質問は後でAIが回答者の言語に翻訳します）。
管理者から渡された資料（商品・文化・サービスの紹介資料など）を読み込み、次の2つを作成してください。

1. トピック紹介記事: 資料の内容を、その文化や商品を初めて知る海外の人にもわかるように紹介する記事（トピック名・タイトル・要約・本文）
2. インタビュー設計: 海外の人の第一印象・興味・利用シーン・価格感・購入意向・懸念・改善要望を引き出すためのテーマと質問

## 記事のルール
- 資料に書かれている事実だけを使い、推測や誇張をしない。資料にない数字や固有名詞を作らない。
- 宣伝文句ではなく、回答者が率直な感想を言えるように客観的に紹介する。
- 日本特有の言葉・習慣・背景には短い説明を添える（海外の人が前提知識なしで読める文章にする）。
- 翻訳しやすいよう、短く明快な文で書く。

## 質問のルール
- 5〜8問。最初は答えやすい質問から始め、徐々に具体的な評価・理由・要望に進む。
- 最初の質問は「最も興味を持った点」を選ぶ質問にし、選択肢には themes と同じ観点を並べる。
- 2問目は回答者とこのトピックの関わり（例: 初めて知った／聞いたことがある／使ったり体験したことがある／仕事で関わっている）を選ぶ質問にする。
- 以降は、第一印象、使ってみたい・体験してみたい場面、魅力に感じる点と気になる点、妥当だと思う価格帯や購入・利用の意向、自国で広めるために必要なこと、などから資料に合うものを選ぶ。
- 価格や購入意向は、資料に価格があればそれを示して妥当かを聞き、なければ「いくらなら買う／試すか」を選択式（通貨に依存しない表現）で聞く。
- 評価・意向などを尋ねる質問は選択式（quick_replies 3〜6件）にする。理由や具体例を聞く質問は自由回答（quick_replies は空配列）にする。
- 最後の質問は「この商品・文化を届けようとしている日本の人たちに伝えたいこと」のような、要望を一言で受け止める質問にする。
- 「その他（自由記述）」はシステムが自動で付けるので、quick_replies に含めない。
- follow_up_guide には、AIインタビュアーが何を引き出すべきか（理由・具体的な場面・自国での比較対象など）、どうなったら次の質問へ進むかを具体的に書く。自由回答の質問では末尾に次の文を付ける:「${FOLLOW_UP_DEPTH_LIMIT_RULE}」
- 質問文は1つの質問で1つのことだけを聞き、「素晴らしいと思いませんか」のような誘導的な言い回しを避ける。
- 政治・政策・法律の話題として扱わない。`;

  const instructionSection = instructions?.trim()
    ? `\n\n## 管理者からの追加の指示\n${instructions.trim()}`
    : "";

  const user = `以下の資料をもとに、トピック紹介記事と市場調査インタビューの設計を作成してください。${instructionSection}

<document>
${documentText}
</document>`;

  return { system, user };
}
